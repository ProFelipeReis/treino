  function esc(s) {
    return String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  }
  function mdInline(s) { return esc(s).replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>'); }
  function stripMd(s) { return String(s == null ? '' : s).replace(/\*\*(.+?)\*\*/g, '$1'); }

  function getDoc(set, id) {
    for (var i = 0; i < set.docs.length; i++) if (set.docs[i].id === id) return set.docs[i];
    return null;
  }

  /** HTML de um dos documentos (uso | privacidade) */
  function html(set, id) {
    var d = getDoc(set, id); if (!d) return '';
    return d.sections.map(function (s) {
      return '<h2>' + esc(s.h) + '</h2>' + s.p.map(function (p) { return '<p>' + mdInline(p) + '</p>'; }).join('');
    }).join('');
  }

  /** Texto puro de todos os documentos (base do hash e do anexo do PDF) */
  function plain(set) {
    return set.docs.map(function (d) {
      return d.title.toUpperCase() + '\n' + d.sections.map(function (s) {
        return s.h + '\n' + s.p.map(stripMd).join('\n');
      }).join('\n');
    }).join('\n\n') + '\n\n' + set.consents.map(function (c) { return c.label; }).join('\n');
  }

  /** SHA-256 (hex) do texto completo. Null se o navegador não suportar. */
  function hash(set) {
    try {
      var data = new TextEncoder().encode(plain(set));
      return crypto.subtle.digest('SHA-256', data).then(function (buf) {
        return Array.prototype.map.call(new Uint8Array(buf), function (b) { return ('0' + b.toString(16)).slice(-2); }).join('');
      }).catch(function () { return null; });
    } catch (e) { return Promise.resolve(null); }
  }

